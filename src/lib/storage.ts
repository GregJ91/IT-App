import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { config } from "./config";

// Screenshots and photos. Stored on local disk for now; swap this module for S3/R2 when hosting is decided.

export const ALLOWED_IMAGE_TYPES: Record<string, string> = {
  "image/png": "png",
  "image/jpeg": "jpg",
  "image/webp": "webp",
  "image/gif": "gif",
  "image/heic": "heic",
  "image/heif": "heif",
};

export class UploadError extends Error {}

export function checkUpload(file: { type: string; size: number; name: string }) {
  if (!ALLOWED_IMAGE_TYPES[file.type]) throw new UploadError(`${file.name} isn't an image. Use PNG, JPG, WebP, GIF or HEIC.`);
  if (file.size > config.maxUploadBytes) throw new UploadError(`${file.name} is over 10 MB. Try a smaller screenshot.`);
}

const root = () => path.resolve(config.uploadDir);

export async function saveUpload(file: File) {
  checkUpload(file);
  const now = new Date();
  const key = `${now.getUTCFullYear()}/${String(now.getUTCMonth() + 1).padStart(2, "0")}/${randomUUID()}.${ALLOWED_IMAGE_TYPES[file.type]}`;
  const full = path.join(root(), key);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, Buffer.from(await file.arrayBuffer()));
  return key;
}

export async function readUpload(key: string) {
  const full = path.resolve(root(), key);
  // Keys are generated by saveUpload, but never read outside the upload folder.
  if (!full.startsWith(root() + path.sep)) throw new UploadError("Bad file key");
  return readFile(full);
}
